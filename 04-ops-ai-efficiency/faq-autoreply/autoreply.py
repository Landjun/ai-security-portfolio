"""
autoreply.py —— 教学/运营 FAQ 自动回复(离线规则版,无需任何 API)。

业务场景:教学/运营每天被大量重复问题占用(怎么报名、怎么退款、课程时间…)。
用关键词规则做一个自动回复助手,先把高频问题挡掉,人工只处理兜底问题,提效明显。

这是"规则版"基线;进阶可换成 RAG/大模型语义匹配(见 06 真实 RAG)。

运行:  python autoreply.py
"""

# 规则库:每条 = (关键词列表, 标准答复)。命中任一关键词即返回该答复。
RULES = [
    (["报名", "怎么报", "如何加入"], "报名方式:点击课程页『立即报名』,支付后自动开通,有问题可发订单号给班主任。"),
    (["退款", "退费", "能退"], "退款政策:开课前可全额退;开课 7 天内按进度退;超过 7 天不支持退款。"),
    (["上课时间", "什么时候上", "开课"], "上课时间:每周二、四晚 8 点直播,错过可看回放,回放永久有效。"),
    (["回放", "录播", "看不了"], "回放在『我的课程-回放』里,如打不开请清缓存或换浏览器,仍不行发截图给客服。"),
    (["发票", "开票"], "发票:在订单页申请,支持电子普票/专票,专票需提供公司税号,3 个工作日内开具。"),
    (["优惠", "便宜", "折扣", "券"], "当前优惠:新学员首单立减 50,老学员转介绍各得 30 元券,详情见活动页。"),
]

FALLBACK = "这个问题我先记下来,转人工老师为你解答(通常 2 小时内回复)。也可以直接说『报名/退款/上课时间/发票/优惠』查看常见答复。"


def auto_reply(question: str):
    """返回 (答复, 是否命中规则)。"""
    for keywords, answer in RULES:
        if any(k in question for k in keywords):
            return answer, True
    return FALLBACK, False


def main():
    demo_questions = [
        "请问怎么报名啊?", "这个课能退款吗", "每周几上课呀", "回放在哪里看",
        "可以开发票吗", "有没有优惠券", "老师我家孩子适合学吗",  # 最后一个走兜底
    ]
    hit = 0
    print("=" * 60)
    print("教学运营 FAQ 自动回复(离线规则版)")
    print("=" * 60)
    for q in demo_questions:
        ans, matched = auto_reply(q)
        hit += matched
        tag = "自动回复" if matched else "转人工"
        print(f"\n用户: {q}\n[{tag}] {ans}")

    rate = hit / len(demo_questions)
    print("\n" + "-" * 60)
    print(f"自动回复命中率: {hit}/{len(demo_questions)} = {rate:.0%}")
    print(f"提效估算:若每天 100 条咨询,可自动处理约 {int(rate*100)} 条,人工只需兜底其余。")


if __name__ == "__main__":
    main()
