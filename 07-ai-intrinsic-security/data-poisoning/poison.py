"""
poison.py —— 生成投毒样本(标签翻转攻击)。

攻击者往训练集里掺入"垃圾短信却标成正常"的样本。
模型学到"这些垃圾特征 = 正常",从而对同类垃圾失明 —— 这就是数据投毒。

现实场景:众包标注、用户举报、可被写入的训练语料,都是投毒入口。
"""

# 投毒样本:内容明显是垃圾,却被恶意标注为正常(label=0)。
# 注意:这里用"多样化"的垃圾(而非同一句的变体),否则雷同毒样本会在特征空间
# 抱团互相掩护,反而难被近邻检测发现(这本身就是一个值得讲的攻防点)。
POISON_TEXTS = [
    "恭喜您获得免费名额请点击",
    "您的快递有补贴点击领取",
    "账户存在异常请点击验证",
    "您中了二等奖点击兑换",
    "投资理财高回报点击咨询",
    "您有一笔退款待领取点击",
]
POISON_LABELS = [0] * len(POISON_TEXTS)   # 全部恶意标成"正常"


def inject(train_texts, train_labels):
    """把投毒样本掺进训练集,返回被污染的训练集。"""
    return (train_texts + POISON_TEXTS, train_labels + POISON_LABELS)
