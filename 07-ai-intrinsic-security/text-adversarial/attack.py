"""
attack.py —— 字符级对抗扰动。

核心思想:把垃圾短信里的关键汉字替换成"人眼几乎看得懂、但模型没见过"的
形近字(这里用简体->繁体作为形近替换)。模型基于字符特征,没学过这些
繁体字,于是判定失效 —— 这就是文本对抗样本。

这类攻击在现实中非常常见(垃圾信息/违规内容用形近字、拼音、插符号规避检测)。
"""

# 简体 -> 形近(繁体)映射。用于"扰动";防御时反向映射即可还原。
HOMOGLYPH = {
    "费": "費", "领": "領", "奖": "獎", "贷": "貸", "链": "鏈",
    "赢": "贏", "话": "話", "点": "點", "击": "擊", "红": "紅",
    "积": "積", "额": "額", "无": "無", "马": "馬", "专": "專",
    "礼": "禮", "联": "聯", "system": "ｓｙｓｔｅｍ",
}
# 反向映射:防御侧把形近字还原回简体
REVERSE = {v: k for k, v in HOMOGLYPH.items()}


SEP = "·"  # 分隔符:插在字符之间,打散模型依赖的"字符组合"特征(人眼仍可读)


def perturb(text: str) -> str:
    """
    对抗扰动 = 形近字替换 + 在每个字符间插入分隔符。
    形近字替换掉模型认识的字;分隔符把"字符组合(bigram/trigram)"特征彻底打散。
    人眼仍能读出这是垃圾短信,模型却被绕过。这是现实中"拆字规避"的真实手法。
    """
    sub = "".join(HOMOGLYPH.get(ch, ch) for ch in text)
    return SEP.join(sub)


def normalize(text: str) -> str:
    """防御侧·输入规范化:去掉分隔符 + 把形近字还原回标准字。"""
    text = text.replace(SEP, "").replace(" ", "")
    return "".join(REVERSE.get(ch, ch) for ch in text)
